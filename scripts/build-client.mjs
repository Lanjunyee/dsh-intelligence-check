import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

// The DSH module loader materializes plugin bundles as lazy CJS factories. The
// page has no build toolchain of its own, so this assembles the three plain
// sources into that exact envelope and commits the artifact.
const root = path.resolve(import.meta.dirname, '..');
const read = file => readFile(path.join(root, file), 'utf8');
const stripExports = source => source.replace(/^export /gm, '');

const fingerprint = stripExports(await read('internal/check/web/modeltrace/fingerprint-core.js'));
const core = stripExports(await read('plugin/client-core.mjs'));
const panel = await read('plugin/client-panel.js');

const bundle = `// Generated by scripts/build-client.mjs from plugin/client-core.mjs,
// plugin/client-panel.js and internal/check/web/modeltrace/fingerprint-core.js.
window.__ModuleLoader__.load({ id: "dsh-intelligence-check", factory: (require) => {
var module = { exports: {} }; var exports = module.exports;
var React = require("react");
${fingerprint}
${core}
${panel}
module.exports = { apply, inject };
return module.exports;
} });
`;

await writeFile(path.join(root, 'plugin', 'client.js'), bundle);
console.log(`wrote plugin/client.js (${Buffer.byteLength(bundle)} bytes)`);
